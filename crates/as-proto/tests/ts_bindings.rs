//! The TypeScript types of the wire protocol (`gui/src/bridge/generated/`) are generated from the Rust
//! types by `ts-rs`. This test regenerates them into a temp folder and fails when the committed files differ,
//! so a change of the protocol that was not followed by a regeneration breaks CI.
//!
//! Regenerate with: `UPDATE_TS_BINDINGS=1 cargo test -p as-proto --test ts_bindings`

use std::collections::BTreeMap;
use std::fs;
use std::path::{Path, PathBuf};

use as_proto::{ClientMsg, Event, Request, Response, ServerMsg};
use ts_rs::{Config, TS};

fn committed_dir() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("../../gui/src/bridge/generated")
}

/// Every `.ts` file under `dir` (recursively), by path relative to `dir` with `/` separators.
fn read_dir_files(dir: &Path) -> BTreeMap<String, String> {
    fn walk(root: &Path, dir: &Path, out: &mut BTreeMap<String, String>) {
        let Ok(entries) = fs::read_dir(dir) else {
            return;
        };
        for entry in entries.flatten() {
            let path = entry.path();
            if path.is_dir() {
                walk(root, &path, out);
            } else if path.extension().is_some_and(|e| e == "ts") {
                let rel = path.strip_prefix(root).unwrap_or(&path);
                let name = rel.to_string_lossy().replace('\\', "/");
                out.insert(name, fs::read_to_string(&path).unwrap_or_default());
            }
        }
    }
    let mut out = BTreeMap::new();
    walk(dir, dir, &mut out);
    out
}

/// Generate every wire type (and, transitively, the as-core types they contain) into `dir`, plus `index.ts`.
fn generate(dir: &Path) {
    // JSON numbers are doubles: the 64-bit counters of the protocol (timestamps, byte counts) stay far below 2^53.
    let cfg = Config::new()
        .with_large_int("number")
        .with_out_dir(dir.to_path_buf());
    ClientMsg::export_all(&cfg).expect("export ClientMsg");
    ServerMsg::export_all(&cfg).expect("export ServerMsg");
    Request::export_all(&cfg).expect("export Request");
    Response::export_all(&cfg).expect("export Response");
    Event::export_all(&cfg).expect("export Event");
    let mut names: Vec<String> = read_dir_files(dir)
        .keys()
        .filter(|n| *n != "index.ts")
        .map(|n| n.trim_end_matches(".ts").to_string())
        .collect();
    names.sort();
    let index: String = std::iter::once(
        "// Generated by crates/as-proto/tests/ts_bindings.rs. Do not edit.\n".to_string(),
    )
    .chain(names.iter().map(|n| format!("export * from './{n}'\n")))
    .collect();
    fs::write(dir.join("index.ts"), index).expect("write index.ts");
}

#[test]
fn committed_typescript_bindings_are_up_to_date() {
    let committed = committed_dir();
    if std::env::var_os("UPDATE_TS_BINDINGS").is_some() {
        let _ = fs::remove_dir_all(&committed);
        fs::create_dir_all(&committed).expect("create generated dir");
        generate(&committed);
        return;
    }
    let tmp = std::env::temp_dir().join(format!("as-ts-bindings-{}", std::process::id()));
    let _ = fs::remove_dir_all(&tmp);
    fs::create_dir_all(&tmp).expect("create temp dir");
    generate(&tmp);
    let fresh = read_dir_files(&tmp);
    let have = read_dir_files(&committed);
    let _ = fs::remove_dir_all(&tmp);

    let mut problems = Vec::new();
    for (name, text) in &fresh {
        match have.get(name) {
            None => problems.push(format!("missing: {name}")),
            Some(old) if old.replace("\r\n", "\n") != text.replace("\r\n", "\n") => {
                problems.push(format!("changed: {name}"))
            }
            Some(_) => {}
        }
    }
    for name in have.keys().filter(|n| !fresh.contains_key(*n)) {
        problems.push(format!("stale: {name}"));
    }
    assert!(
        problems.is_empty(),
        "gui/src/bridge/generated is out of date ({}). Run: UPDATE_TS_BINDINGS=1 cargo test -p as-proto --test ts_bindings",
        problems.join(", ")
    );
}
